# -*- coding: utf-8 -*-
"""Определение «продолжения» генерации: «то же самое, но спиной».

Когда пользователь просит «то же самое, но X», это продолжение последней
генерации: берём её промт как базу, её картинку как референс, её seed, и
меняем только X.
"""
from __future__ import annotations

import re
from typing import List, Optional


CONTINUATION_TRIGGERS: List[str] = [
    # прямые отсылки на «то же самое»
    "то же самое", "тоже самое", "то же", "так же", "аналогично",
    "тот же", "такое же", "такой же", "такую же", "такая же", "та же",
    # повтор / продолжение
    "ещё раз", "еще раз", "повтори", "повтор", "снова", "опять",
    "продолжай", "продолжи", "а теперь", "теперь то же",
    # правка кадра / ракурс
    "спиной", "сзади", "со спины", "в профиль", "анфас",
    "с другой стороны", "в другом ракурсе", "другой ракурс",
    "сбоку", "спереди", "вид сзади", "вид сбоку", "вид спереди",
    "в полный рост", "полный рост", "крупнее",
    "с изменениями", "с небольшими изменениями", "по-другому", "иначе",
]

# Сильные маркеры — сами по себе значат «продолжай предыдущий кадр».
_STRONG_TRIGGERS: List[str] = [
    "то же самое", "тоже самое", "то же", "так же", "аналогично",
    "тот же", "такое же", "такой же", "такую же", "такая же", "та же",
    "ещё раз", "еще раз", "повтори", "повтор",
    "снова", "опять", "продолжай", "продолжи", "теперь то же",
]

# Слабые маркеры правки — нужна поддержка словами «но/только/теперь/ещё».
_VIEW_TRIGGERS: List[str] = [
    "спиной", "сзади", "со спины", "в профиль", "анфас",
    "с другой стороны", "в другом ракурсе", "другой ракурс",
    "сбоку", "спереди", "вид сзади", "вид сбоку", "вид спереди",
    "в полный рост", "полный рост", "крупнее", "ближе", "дальше",
    "с изменениями", "с небольшими изменениями", "по-другому", "иначе",
]

# Слова-поддержка для слабых маркеров.
_SUPPORT_WORDS: List[str] = [
    "не", "но ", " но ", "только", "теперь", "а теперь",
    "ещё", "еще", "же", "сделай", "покажи", "нарисуй", "осталось", "оставляя",
]

_RESET_PHRASES: List[str] = [
    "с нуля", "заново с нуля", "новую картин", "новое изображ",
    "новую фот", "другую картин", "другой персонаж", "другой герой",
    "другое изображ", "другая картин", "без референс", "без фото",
    "не то же", "не то самое", "не надо", "отмена", "стоп",
    "вместо этого", "не по прошлому", "забудь про прошло",
]


def _norm(text: str) -> str:
    return " ".join((text or "").lower().replace("ё", "е").split())


def is_reset_request(user_text: str) -> bool:
    """Явный сброс — пользователь просит новую картинку с нуля."""
    s = _norm(user_text)
    return any(r in s for r in _RESET_PHRASES)


def is_continuation(user_text: str) -> bool:
    """
    Определяет, продолжает ли запрос предыдущую генерацию.

    Если True — следующий промт строится на основе последней записи истории:
    её промт как база, её output_path как референс, её seed и параметры.

    Примеры:
        "то же самое, но спиной"          -> True
        "а теперь в полный рост"          -> True
        "повтори"                          -> True
        "ещё раз, только чтобы видно было ноги" -> True
        "сгенерируй заново с нуля"        -> False (явный сброс)
        "нарисуй кота в шляпе"             -> False (новая сцена)
    """
    s = _norm(user_text)
    if len(s) < 4:
        return False
    if is_reset_request(s):
        return False
    for w in _STRONG_TRIGGERS:
        if w in s:
            return True
    view = next((w for w in _VIEW_TRIGGERS if w in s), "")
    if view:
        for sup in _SUPPORT_WORDS:
            if sup in s:
                return True
        # «сделай в профиль», «нарисуй спиной» без «но/только» — тоже правка кадра
        if re.search(
            r"(сделай|покажи|нарисуй|изобрази|покажи её|покажи его)\s+(\w+\s+)*(спиной|сзади|со спины|в профиль|анфас|в полный рост|крупнее|сбоку|спереди|в другом ракурсе)",
            s,
        ):
            return True
    # «а теперь / теперь» без явной привязки — продолжить только с отсылкой на прошлое
    if "а теперь" in s or "теперь" in s:
        for ref in ("же", "снова", "опять", "повтори", "продолжи", "ещё", "еще", "сделай"):
            if ref in s:
                return True
    return False


def continuation_trigger(user_text: str) -> str:
    """Какой триггер сработал (для логов)."""
    s = _norm(user_text)
    for w in _STRONG_TRIGGERS:
        if w in s:
            return w
    for w in _VIEW_TRIGGERS:
        if w in s:
            return w
    return ""